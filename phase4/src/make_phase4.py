analysis = analysis.replace('# Phase 4 analysis (generated by analyze.py)' + chr(10), '')
runs = load(os.path.join(RES, 'runs.jsonl'))
sad = load(os.path.join(RES, 'runs_sadical.jsonl'))
manifest = load(os.path.join(INST, 'MANIFEST.jsonl'))
f7 = [r for r in load(os.path.join(INST, 'sc23', 'labels_f7.jsonl')) if r['cadical'] in ('SAT', 'UNSAT')]
total_jobs = (len(manifest) + len(f7)) * 3
done = Counter(r['mode'] for r in runs)
sched = open(os.path.join(P4, 'schedule_decision.md'), encoding='utf-8').read().strip()
verdict_block = open(os.path.join(P4, 'verdict.md'), encoding='utf-8').read().strip() if os.path.exists(os.path.join(P4, 'verdict.md')) else '(verdict.md missing)'

# supplementary SaDiCaL table
sad_rows = ['| family | instance | size | SaDiCaL result | conflicts | prunes | reducts | wall (s) | dpr-trim |', '|---|---|---|---|---|---|---|---|---|']
for r in sorted(sad, key=lambda r: (r['family'], r['size'], r['name'])):
    if r['status'] == 'UNKNOWN' and r['wall'] >= 3600:
        r['status'] = 'TIMEOUT (3600 s cap)'
    sad_rows.append('| %s | %s | %s | %s | %s | %s | %s | %.1f | %s |' % (r['family'], r['name'], r['size'], r['status'], r.get('conflicts'), r.get('pruned'), r.get('reducts'), r['wall'], r.get('dprtrim', '-')))

# per-mode completion
comp = ['| mode | jobs recorded | of | solved | timeouts | crashes |', '|---|---|---|---|---|---|']
for m in ('sdcl', 'plain', 'unfiltered'):
    rs = [r for r in runs if r['mode'] == m]
    comp.append('| %s | %d | %d | %d | %d | %d |' % (m, len(rs), total_jobs // 3, sum(1 for r in rs if r.get('status') in ('SATISFIABLE', 'UNSATISFIABLE')),
                                                 sum(1 for r in rs if str(r.get('status')).startswith('TIMEOUT')), sum(1 for r in rs if r.get('status') == 'CRASH')))


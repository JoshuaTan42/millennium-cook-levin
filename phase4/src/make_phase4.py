RES = os.path.join(P4, 'results'); INST = os.path.join(P4, 'instances')


def load(p):
    out = []
    if os.path.exists(p):
        for l in open(p):
            try:
                out.append(json.loads(l))
            except Exception:
                pass
    return out


subprocess.run([sys.executable, os.path.join(HERE, 'analyze.py')], capture_output=True, text=True)
analysis = open(os.path.join(RES, 'analysis.md'), encoding='utf-8').read()
# demote the analysis headings under section 4 of this report

"""Append the Phase 4 results section to NOTES.md (run once at the stopping point, after make_phase4.py)."""
import os, json, time, re
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
P4 = os.path.normpath(os.path.join(HERE, '..')); ROOT = os.path.normpath(os.path.join(P4, '..'))
RES = os.path.join(P4, 'results'); INST = os.path.join(P4, 'instances')

runs = [json.loads(l) for l in open(os.path.join(RES, 'runs.jsonl')) if l.strip()]
analysis = open(os.path.join(RES, 'analysis.md'), encoding='utf-8').read()
verdict = open(os.path.join(P4, 'verdict.md'), encoding='utf-8').read().strip()


def section(name):
    m = re.search(r'## %s.*?(?=\n## |\Z)' % re.escape(name), analysis, re.S)
    return m.group(0).strip() if m else '(missing)'


def fired(k):
    m = re.search(r'\*\*%s fired: (YES|NO)\*\*' % k, analysis)
    return m.group(1) if m else '?'


c = Counter((r['mode'], 'solved' if r.get('status') in ('SATISFIABLE', 'UNSATISFIABLE') else ('timeout' if str(r.get('status')).startswith('TIMEOUT') else 'other')) for r in runs)
lines = []
P = lines.append
